"""macOS pasteboard backend for nspire_bridge (NSPasteboard through pyobjc).

The same names as nspire_clip_win: clip_get, write_text, seq, clip_snapshot,
clip_restore, ClipSnapshot and ProcessLock. pyobjc is imported on first use, so
this module imports on any OS (the offline tests fake the pasteboard).

- Change counter: NSPasteboard.changeCount, read without touching the contents.
- Bridge traffic is written for this Mac only (no Universal Clipboard) and
  marked with the nspasteboard.org types that clipboard managers skip:
  org.nspasteboard.TransientType, ConcealedType and AutoGeneratedType.
- Snapshots keep every type of every pasteboard item (several items when files
  are copied). A restored copy stays on this Mac and is marked transient, so
  history doesn't get it twice; types the user's copy had (Concealed from a
  password manager, say) are kept.
- The cross-process lock is an flock() on a file in ~/Library/Caches/nspire-mcp;
  the OS releases it if the process dies.

Not yet tried on a real Mac.
"""
from __future__ import annotations

import contextlib
import logging
import os
import re
import sys
import tempfile
import threading
import time
from dataclasses import dataclass, field
from types import SimpleNamespace

log = logging.getLogger("nspire")

SNAPSHOT_MAX_BYTES = 128 * 2**20
TEXT_TYPE = "public.utf8-plain-text"     # NSPasteboardTypeString
UTF16_TYPE = "public.utf16-plain-text"   # some programs write only this
TRANSIENT_TYPE = "org.nspasteboard.TransientType"   # will be replaced shortly: don't record it
CONCEALED_TYPE = "org.nspasteboard.ConcealedType"   # don't show or keep it
AUTOGEN_TYPE = "org.nspasteboard.AutoGeneratedType"  # written by a program, not copied by the user
TRAFFIC_MARKS = (TRANSIENT_TYPE, CONCEALED_TYPE, AUTOGEN_TYPE)
CURRENT_HOST_ONLY = 1  # NSPasteboardContentsCurrentHostOnly: not sent to other devices
SETTLE_S = 0.05        # how long an empty pasteboard right after a change may still be filling

_lock = threading.RLock()  # one pasteboard operation at a time in this process
_cocoa_ns: SimpleNamespace | None = None


def _cocoa() -> SimpleNamespace:
    """pb (the general pasteboard), Item (NSPasteboardItem), data(bytes) -> NSData, and pool()."""
    global _cocoa_ns
    if _cocoa_ns is None:
        if sys.platform != "darwin":
            raise RuntimeError(f"The TI-Nspire bridge works on Windows and macOS only, not {sys.platform}.")
        try:
            import objc
            from AppKit import NSPasteboard, NSPasteboardItem
            from Foundation import NSData
        except ImportError as e:
            raise RuntimeError("The macOS clipboard needs pyobjc-framework-Cocoa; run the script with "
                               "`uv run --script`, which installs it.") from e
        _cocoa_ns = SimpleNamespace(pb=NSPasteboard.generalPasteboard(), Item=NSPasteboardItem,
                                    data=lambda b: NSData.dataWithBytes_length_(b, len(b)),
                                    pool=objc.autorelease_pool)
    return _cocoa_ns


@contextlib.contextmanager
def _pasteboard():
    c = _cocoa()
    with _lock, c.pool():  # threads other than the main one have no autorelease pool of their own
        yield c


def _settle(pb) -> None:
    """Wait briefly if the pasteboard is empty: another program may be between
    clearing it and writing (macOS doesn't lock it while a program writes)."""
    n = pb.changeCount()
    deadline = time.monotonic() + SETTLE_S
    while not pb.pasteboardItems() and time.monotonic() < deadline:
        time.sleep(0.01)
        if pb.changeCount() != n:
            return  # changed again: the caller will look at the new contents


def seq() -> int:
    """The pasteboard's change counter."""
    with _pasteboard() as c:
        return int(c.pb.changeCount())


def clip_get() -> str | None:
    with _pasteboard() as c:
        _settle(c.pb)
        s = c.pb.stringForType_(TEXT_TYPE)
        return None if s is None else str(s)


def write_text(text: str, transient: bool) -> int:
    """Replace the pasteboard with text. Returns the change count after the write.

    transient: bridge traffic, kept on this Mac and marked so clipboard managers skip it.
    """
    with _pasteboard() as c:
        item = c.Item.alloc().init()
        item.setString_forType_(text, TEXT_TYPE)
        if transient:
            for t in TRAFFIC_MARKS:
                item.setData_forType_(c.data(b""), t)
            n = c.pb.prepareForNewContentsWithOptions_(CURRENT_HOST_ONLY)
        else:
            n = c.pb.clearContents()
        if not c.pb.writeObjects_([item]):
            raise RuntimeError("Could not write to the macOS pasteboard.")
        return int(n)


# ---------------------------------------------------------------- snapshots

@dataclass
class ClipSnapshot:
    """A copy of the pasteboard: one {type: bytes} dict per pasteboard item."""
    items: list[dict[str, bytes]] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)

    def text(self) -> str | None:
        for item in self.items:
            if TEXT_TYPE in item:
                return item[TEXT_TYPE].decode("utf-8", errors="replace")
            if UTF16_TYPE in item:
                return item[UTF16_TYPE].decode("utf-16-le", errors="replace")
        return None


def clip_snapshot() -> ClipSnapshot:
    """Copy every type of every item on the pasteboard."""
    with _pasteboard() as c:
        _settle(c.pb)
        snap, total = ClipSnapshot(), 0
        for item in c.pb.pasteboardItems() or []:
            got: dict[str, bytes] = {}
            for t in item.types() or []:
                t = str(t)
                try:
                    # This asks the program that copied for data it promised
                    # but hasn't written yet; nil if it can't (it quit, say).
                    d = item.dataForType_(t)
                except Exception:
                    d = None
                data = None if d is None else bytes(d)
                if data is None or total + len(data) > SNAPSHOT_MAX_BYTES:
                    snap.skipped.append(t)
                    continue
                total += len(data)
                got[t] = data
            if got:
                snap.items.append(got)
        if snap.skipped:
            log.debug("pasteboard snapshot skipped types %s", snap.skipped)
        return snap


def clip_restore(snap: ClipSnapshot | None) -> None:
    """Put a snapshot back (this Mac only, marked transient). None empties the pasteboard."""
    with _pasteboard() as c:
        items = []
        for types in snap.items if snap else []:
            item = c.Item.alloc().init()
            for t, data in types.items():
                if not item.setData_forType_(c.data(data), t):
                    log.warning("could not restore pasteboard type %s", t)
            items.append(item)
        if items and snap and TRANSIENT_TYPE not in snap.items[0]:
            # The copy went into history when the user made it; don't add it twice.
            items[0].setData_forType_(c.data(b""), TRANSIENT_TYPE)
        c.pb.prepareForNewContentsWithOptions_(CURRENT_HOST_ONLY)
        if items and not c.pb.writeObjects_(items):
            log.warning("could not restore the pasteboard")


# ---------------------------------------------------------------- cross-process lock

def _lock_dir() -> str:
    if sys.platform == "darwin":
        return os.path.expanduser("~/Library/Caches/nspire-mcp")
    return tempfile.gettempdir()


class ProcessLock:
    """One bridge request at a time across processes: flock() on a lock file.

    Each acquire opens the file anew, so two ProcessLock objects (or two
    threads) exclude each other even within one process. The OS drops the
    lock when the file is closed or the process dies.
    """

    def __init__(self, name: str, directory: str | None = None) -> None:
        self.path = os.path.join(directory or _lock_dir(), re.sub(r"[^\w.-]", "_", name) + ".lock")
        self._fd: int | None = None

    def acquire(self, timeout_s: float) -> bool:
        """Wait at most timeout_s; True if the lock is now held."""
        import fcntl
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        fd = os.open(self.path, os.O_RDWR | os.O_CREAT, 0o600)
        deadline = time.monotonic() + max(timeout_s, 0)
        while True:
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)  # pyright: ignore[reportAttributeAccessIssue]
            except BlockingIOError:
                if time.monotonic() >= deadline:
                    os.close(fd)
                    return False
                time.sleep(0.01)
                continue
            except BaseException:
                os.close(fd)
                raise
            self._fd = fd
            return True

    def release(self) -> None:
        fd, self._fd = self._fd, None
        if fd is not None:
            os.close(fd)  # closing the only descriptor of this open file drops the lock
